export type IconName = keyof typeof ICONS

/** 把图标网格转成 SVG path（同一行相邻像素合并成一段） */
const cache = new Map<string, { full: string; half: string; accent: string }>()
export function iconPaths(name: IconName) {
  const hit = cache.get(name)
  if (hit) return hit
  const rows = ICONS[name]
  let full = ''
  let half = ''
  let accent = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === '.') {
        x++
        continue
      }
      let w = 1
      while (x + w < row.length && row[x + w] === ch) w++
      const seg = `M${x} ${y}h${w}v1h-${w}z`
      if (ch === '#') full += seg
      else if (ch === '+') half += seg
      else if (ch === 'o') accent += seg
      x += w
    }
  })
  const r = { full, half, accent }
  cache.set(name, r)
  return r
}
